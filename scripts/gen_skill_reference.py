"""Regenerate the igctl skill's reference files from the live CLI definition.

uv run python scripts/gen_skill_reference.py
"""

from __future__ import annotations

import json
import re
from pathlib import Path
from typing import Any

import typer.main
from typer.testing import CliRunner

from igctl.cli.main import app

REPO = Path(__file__).resolve().parent.parent
REFS = REPO / "skills" / "igctl" / "references"

HEADER = """# igctl command reference

Generated from the CLI by `scripts/gen_skill_reference.py`; do not edit by hand.

Global options go **before** the group: `igctl [--json] [-a ALIAS] [-b graph|private] [--dry-run] GROUP COMMAND ...`

| Global option | Meaning |
|---|---|
| `--json` | Machine-readable JSON on stdout (use whenever you parse output) |
| `-a, --account ALIAS` | Account alias to act as (default: `default_account`, or env `IGCTL_ACCOUNT`) |
| `-b, --backend graph\\|private` | Override the account's backend for this command |
| `--dry-run` | Show what would happen; perform no writes |
| `--version` | Print the version |

## Authentication setup (the user runs this, never the agent)

Private backend (any account; can do everything; violates Instagram's Terms):

    igctl auth login main --backend private -u USERNAME --default   # prompts for password
    igctl auth login main --backend private -u USERNAME --2fa 123456

Graph backend (Business/Creator account plus a Meta app access token):

    igctl auth login brand --backend graph --host graph.instagram.com --token "IGAA..." --default
    igctl auth login brand --backend graph --host graph.facebook.com --token "EAA..." --ig-user-id 1784...

Secrets live in the OS keyring (service `igctl`) or env `IGCTL_<ALIAS>_TOKEN` / `IGCTL_<ALIAS>_PASSWORD`.
Config: `~/.igctl/config.yaml` (override the directory with env `IGCTL_HOME`).
"""


def _param_line(p: Any) -> str | None:
    if p.name == "help" or getattr(p, "hidden", False):
        return None
    # Typer >= 0.27 vendors click, so use duck typing rather than click's classes.
    if p.param_type_name == "argument":
        name = p.human_readable_name.upper()
        if p.nargs == -1:
            name += "..."
        req = "required" if p.required else "optional"
        return f"| `{name}` | argument, {req} | |"
    flags = ", ".join(p.opts)
    if p.secondary_opts:
        flags += " / " + ", ".join(p.secondary_opts)
    kind = "flag" if p.is_flag else (p.type.name if p.type else "value")
    if p.multiple:
        kind += ", repeatable"
    if p.required:
        kind += ", required"
    default = ""
    if p.show_default is not False and p.default not in (None, False, (), []) and not p.is_flag:
        default = f" (default: `{p.default}`)"
    help_text = (p.help or "").replace("|", "\\|").replace("\n", " ")
    return f"| `{flags}` | {kind} | {help_text}{default} |"


def render() -> str:
    root = typer.main.get_command(app)
    out = [HEADER]
    ctx = root.context_class(root)
    for gname in sorted(root.list_commands(ctx)):
        group = root.get_command(ctx, gname)
        if not hasattr(group, "list_commands"):
            continue
        out.append(f"\n## {gname}\n")
        if group.help:
            out.append(group.help.strip().split("\n")[0] + "\n")
        gctx = group.context_class(group, parent=ctx)
        for cname in group.list_commands(gctx):
            cmd = group.get_command(gctx, cname)
            if cmd is None or cmd.hidden:
                continue
            out.append(f"\n### `igctl {gname} {cname}`\n")
            if cmd.help:
                out.append(cmd.help.strip().replace("\b\n", "") + "\n")
            rows = [r for p in cmd.params if (r := _param_line(p))]
            if rows:
                out.append("\n| Parameter | Kind | Description |\n|---|---|---|")
                out.extend(rows)
                out.append("")
    return _tidy("\n".join(out))


def _tidy(text: str) -> str:
    return re.sub(r"\n{3,}", "\n\n", text).rstrip() + "\n"


AUTOMATION_HEADER = """# igctl automation rules

Generated by `scripts/gen_skill_reference.py`; do not edit by hand.

A rules file is YAML with optional `defaults` (merged into every rule) and a list of `rules`.
Each rule has these fields: `name`, `account`, `backend`, `enabled`, `every` (an interval such as `15m` or `2h`, or a
UTC cron expression such as `0 9 * * *`), `trigger: {type: ..., options}`,
`filter: {keywords, regex, match: any|all, exclude}`, `action: {...}` and
`limits: {max_per_run, min_delay, max_delay}`.

Workflow for agents:

1. `igctl automate validate rules.yaml` checks the schema and shows what the file defines.
2. `igctl --dry-run automate run rules.yaml --force` previews every rule and performs no writes.
   Show the result to the user.
3. Once the user approves, run `igctl automate run rules.yaml` (only the rules that are due),
   or `--loop` to keep it running as a service.
4. `igctl automate status` shows each rule's last and next run.
   `igctl automate log --limit 50` shows the actions taken.

Every write goes through the account's guard: human-like delays plus rolling 24h caps per action.
Triggers marked `private` need the private backend, which carries a risk of account restriction.
Keep `max_per_run` small.

## Triggers

Options marked with `*` are required.

| Trigger | What it does | Trigger options | Action options | Default max/run | Backend |
|---|---|---|---|---|---|
"""


def render_automation() -> str:
    res = CliRunner().invoke(app, ["--json", "automate", "list-triggers"])
    if res.exit_code != 0:
        raise SystemExit(f"automate list-triggers failed:\n{res.output}")
    rows = [
        f"| `{t['trigger']}` | {t['description']} | {t['trigger_options']} | "
        f"{t['action_options']} | {t['default_max']} | {t['backend']} |"
        for t in json.loads(res.stdout)
    ]
    example = (REPO / "examples" / "rules.yaml").read_text(encoding="utf-8")
    return _tidy(
        AUTOMATION_HEADER
        + "\n".join(rows)
        + "\n\n## Annotated example (`examples/rules.yaml`)\n\n```yaml\n"
        + example.rstrip()
        + "\n```\n"
    )


if __name__ == "__main__":
    REFS.mkdir(parents=True, exist_ok=True)
    for name, text in (("commands.md", render()), ("automation.md", render_automation())):
        (REFS / name).write_text(text, encoding="utf-8")
        print(f"wrote {REFS / name}")
